import { Injectable } from '@nestjs/common';
import { Algorithm, hash as argon2Hash, verify as argon2Verify } from '@node-rs/argon2';

/**
 * HOW A DASHBOARD PASSWORD IS STORED.
 *
 * `docs/design/B1-auth-and-data.md` §2. Argon2id via `@node-rs/argon2`, which
 * ships prebuilt platform binaries — on the host measured in §0 that is not a
 * preference but the only way an Argon2 library installs at all: there is no
 * MSVC toolset, no Windows SDK and no working Python, so anything needing
 * node-gyp fails at install time and takes `pnpm install` down with it.
 *
 * ## This is the HASHED kind of credential, and never the other one
 *
 * §7: a dashboard password is hashed and is never needed in plaintext; an
 * app-under-test credential must be DECRYPTABLE at run time. They look alike
 * and are opposites, so they share no table, no type and no vocabulary. Nothing
 * here encrypts, and nothing here can return a plaintext.
 *
 * ## The cost was MEASURED, and the measurement disagrees with the target
 *
 * Measured on this host (Node 24.19.0, win32-x64) on 2026-10-30, five runs
 * after a warm-up, at the parameters below:
 *
 *     m=19456, t=2, p=1   ->    8-9 ms   (median 8)
 *     verify               ->      8 ms
 *
 * §2 says a hash "should take roughly 100-500 ms on the machine that serves
 * logins" and that "too fast and the parameters are decorative". **Eight
 * milliseconds is between twelve and sixty times under that band**, so by §2's
 * own standard these parameters are decorative on this machine — they are
 * OWASP's FLOOR, and this host is fast enough that the floor costs it almost
 * nothing.
 *
 * Measured alternatives, same host, same method, so the recommendation is a
 * number rather than a guess:
 *
 *     m=19456,  t=12, p=1  ->   48 ms   still under
 *     m=65536,  t=3,  p=1  ->   56 ms   still under
 *     m=65536,  t=6,  p=1  ->  110 ms   in band
 *     m=131072, t=4,  p=1  ->  163 ms   in band
 *
 * The parameters below are §2's, because that is the decision on record. The
 * measurement is recorded BESIDE them rather than in prose somewhere, so the
 * two cannot be read apart — a number that will be quoted carries its qualifier
 * at the point of measurement (§"weld a headline number to the assumption").
 * Raising them is a one-line change here plus a `needsRehash` pass that happens
 * automatically on each user's next login.
 */

/** The stored form: a PHC string. Branded so it cannot be mixed with any other. */
export type PasswordHash = string & { readonly __passwordHash: unique symbol };

/**
 * §2's parameters, and the single place they are written.
 *
 * `memoryCost` is KiB — 19456 KiB is 19 MiB. `parallelism: 1` keeps a login's
 * cost predictable under concurrency: raising it multiplies the cost of each
 * concurrent login rather than dividing it.
 */
export const ARGON2_POLICY = {
  algorithm: Algorithm.Argon2id,
  memoryCost: 19_456,
  timeCost: 2,
  parallelism: 1,
  outputLen: 32,
} as const;

/** What the PHC string says, when it can be read. */
interface StoredParameters {
  algorithm: string;
  version: number;
  memoryCost: number;
  timeCost: number;
  parallelism: number;
}

/**
 * `$argon2id$v=19$m=19456,t=2,p=1$<salt>$<hash>`.
 *
 * Parsed rather than assumed: the whole point of a PHC string is that a verify
 * never has to be TOLD which parameters produced it, so reading them back out
 * is what makes `needsRehash` possible at all.
 */
const PHC = /^\$(argon2(?:id|i|d))\$v=(\d+)\$m=(\d+),t=(\d+),p=(\d+)\$([^$]+)\$([^$]+)$/;

export function parseStoredParameters(stored: string): StoredParameters | undefined {
  const match = PHC.exec(stored);
  if (!match) return undefined;
  return {
    algorithm: match[1]!,
    version: Number(match[2]),
    memoryCost: Number(match[3]),
    timeCost: Number(match[4]),
    parallelism: Number(match[5]),
  };
}

export abstract class PasswordHasher {
  /** Returns a PHC string. The algorithm and every parameter live INSIDE it. */
  abstract hash(plaintext: string): Promise<PasswordHash>;
  /**
   * Constant-time, and reads the parameters out of the STORED value rather than
   * from the policy — otherwise raising the policy would invalidate every
   * existing password instead of upgrading it.
   */
  abstract verify(stored: string, plaintext: string): Promise<boolean>;
  /** True when `stored` was produced under weaker parameters than policy. */
  abstract needsRehash(stored: string): boolean;
}

@Injectable()
export class Argon2PasswordHasher extends PasswordHasher {
  async hash(plaintext: string): Promise<PasswordHash> {
    // The salt is generated by the library: 16 random bytes, per password, and
    // never derived from the email or the user id.
    return (await argon2Hash(plaintext, { ...ARGON2_POLICY })) as PasswordHash;
  }

  async verify(stored: string, plaintext: string): Promise<boolean> {
    try {
      return await argon2Verify(stored, plaintext);
    } catch {
      // A MALFORMED stored value is FALSE, not an exception.
      //
      // `argon2Verify` throws on a hash it cannot parse — a truncated row, an
      // empty string, a value from some other scheme. A caller that had to
      // try/catch would eventually have one that did not, and an exception
      // escaping a login handler is a 500 where the honest answer is "those
      // credentials are wrong". It also must not be distinguishable from a
      // wrong password (§3): a 500 for one account and a 401 for another is
      // user enumeration with extra steps.
      return false;
    }
  }

  needsRehash(stored: string): boolean {
    const parsed = parseStoredParameters(stored);
    // Unreadable, or not Argon2id at all: re-hash it. This is only ever reached
    // AFTER a successful verify, so an unparseable value cannot get here — and
    // if it somehow did, re-hashing is the harmless direction.
    if (!parsed) return true;
    if (parsed.algorithm !== 'argon2id') return true;
    // WEAKER, not merely different. A hash stored under parameters STRONGER than
    // policy is left alone: downgrading somebody's password because the policy
    // moved down would be the opposite of what this is for.
    return (
      parsed.memoryCost < ARGON2_POLICY.memoryCost ||
      parsed.timeCost < ARGON2_POLICY.timeCost ||
      parsed.parallelism < ARGON2_POLICY.parallelism
    );
  }
}

/**
 * The dummy hash an unknown-user login is verified against.
 *
 * §3: a login for an address with no account must take the same path and the
 * same time as one for a real account, or the response time says whether the
 * address exists. So the login handler always runs a verify — against a real
 * account's stored hash, or against this.
 *
 * Generated once at module load from a random password nobody holds, rather
 * than hard-coded: a constant in the source would be a published hash of a
 * known input, which is pointless to publish and invites somebody to "fix" it
 * by reusing a real one. The password is discarded immediately; nothing can
 * verify against it on purpose.
 */
export async function makeDummyHash(hasher: PasswordHasher): Promise<string> {
  const unknowable = `${Date.now()}-${Math.random()}-${Math.random()}`;
  return hasher.hash(unknowable);
}
